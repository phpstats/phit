def parse_stubs():
    text = (ROOT / 'stubs' / 'phit.php').read_text()
    functions = {}
    for doc, name, args, ret in re.findall(r'/\*\*((?:(?!\*/).)*?)\*/\nfunction (\w+)\(([^)]*)\): ([^{]+?) \{\}', text, re.S):
        lines = [re.sub(r'^\s*\* ?', '', line) for line in doc.strip('\n').split('\n')]
        description, tags, current = [], [], None
        for line in lines:
            if line.startswith('@'):
                current = [line]
                tags.append(current)
            elif current is not None:
                current.append(line)
            elif line.strip():
                description.append(line.strip())
        params = []
        for arg in [a.strip() for a in args.split(', ') if a.strip()]:
            m = re.match(r'(\S+) \$(\w+)(?: = (.+))?$', arg)
            params.append({'type': m[1], 'name': m[2], 'default': m[3]})
        docs, returns, throws, deprecated = {}, None, None, None
        for tag in tags:
            body = '\n'.join(tag)
            if body.startswith('@param'):
                m = re.search(r'\$(\w+)(.*)', body, re.S)
                docs[m[1]] = ' '.join(m[2].split())
            elif body.startswith('@return'):
                returns = body[len('@return'):].strip()
            elif body.startswith('@throws'):
                throws = ' '.join(body[len('@throws'):].replace('\\Exception', '').split())
            elif body.startswith('@deprecated'):
                deprecated = ' '.join(body[len('@deprecated'):].split())
        for p in params:
            p['doc'] = docs.get(p['name'], '')
        functions[name] = {'name': name, 'description': description, 'params': params, 'return_type': ret.strip(),
                           'returns': returns, 'throws': throws, 'deprecated': deprecated}
    classes = {}
    for doc, name, body in re.findall(r'/\*\*((?:(?!\*/).)*?)\*/\nfinal class (\w+)\n\{\n(.*?)\n\}', text, re.S):
        methods = []
        for mdoc, mname, margs, mret in re.findall(
                r'/\*\*((?:(?!\*/).)*?)\*/\n  public function (\w+)\(([^)]*)\)(?:: ([^{]+?))? \{\}', body, re.S):
            mlines = [re.sub(r'^\s*\* ?', '', line).rstrip() for line in mdoc.strip('\n').split('\n')]
            methods.append({'name': mname, 'args': margs, 'return_type': (mret or '').strip(),
                            'doc': [line for line in mlines if line.strip()]})
        classes[name] = {'description': [re.sub(r'^\s*\* ?', '', l).strip() for l in doc.strip('\n').split('\n')
                                         if l.strip(' *')], 'methods': methods}
    return functions, classes


def purpose(fn):
    if fn['name'] in PURPOSE:
        return PURPOSE[fn['name']]
    first = ' '.join(fn['description'])
    sentence = re.split(r'(?<=[.;:])\s', first, maxsplit=1)[0].rstrip(':;')
    return sentence if sentence.endswith('.') else sentence + '.'


def signature(fn):
    if not fn['params']:
        return f"Phit\\{fn['name']}(): {fn['return_type']}"
    lines = [f"    {p['type']} ${p['name']}" + (f" = {p['default']}" if p['default'] else '') + ',' for p in fn['params']]
    return f"Phit\\{fn['name']}(\n" + '\n'.join(lines) + f"\n): {fn['return_type']}"


def cell(text):
    return text.replace('|', '\\|').replace('\n', ' ')


def entry(fn, level='###'):
    out = [f"{level} `{fn['name']}()` {{#{fn['name']}}}", '']
    out += [' '.join(fn['description']), '']
    out += ['```php', signature(fn), '```', '']
    if fn['params']:
        out += ['| Parameter | Type | Default | Description |', '| --- | --- | --- | --- |']
        for p in fn['params']:
            default = f"`{cell(p['default'])}`" if p['default'] else 'required'
            out.append(f"| `${p['name']}` | `{cell(p['type'])}` | {default} | {cell(p['doc'])} |")
        out.append('')
    if fn['returns'] and '\n' in fn['returns']:
        out += ['**Returns**', '', '```php', fn['returns'], '```', '']
    else:
        out += [f"**Returns** `{cell(fn['returns'] or fn['return_type'])}`", '']
    if fn['throws']:
        out += [f"**Errors** {fn['throws']}", '']
    guide, example = GUIDES.get(fn['name'], (None, None))
    links = [f'[Details]({guide})'] if guide else []
    if example:
        links.append(f'[Example]({example})')
    if links:
        out += ['**See also** ' + ' · '.join(links), '']
    return out


def page(file, title, intro, sections, functions):
    out = ['---', f'title: "{title}"', '---', '', GENERATED, intro, '']
    for heading, names in sections:
        out += [f'## {heading}', '']
        for name in names:
            out += entry(functions[name])
    return file, '\n'.join(out).rstrip() + '\n'


def family_of(name):
    m = re.match(r'dist_(nbinom_mu|[a-z]+?)_((?:log)?(?:pdf|pmf|cdf|sf)|quantile|rng)(_array)?$', name)
    return (m[1], m[2], bool(m[3])) if m and m[1] in FAMILIES else None


def distributions_page(functions):
    out = ['---', 'title: "Distribution functions"', '---', '', GENERATED,
           'Densities, masses, tails, and quantiles of 12 families in 13 parameterizations, each in a scalar form and '
           'an `_array` batch form, with a seeded sampler. Inputs, results, and error codes follow the '
           '[shared rules](../reference-utilities.qmd#distribution-functions); families and domains are in '
           '[Probability distributions](../distributions.qmd).', '']
    for family in FAMILIES:
        ops = DISCRETE if f'dist_{family}_pmf' in functions else CONTINUOUS
        sample = functions[f'dist_{family}_cdf']
        header = FAMILY_NAMES[family]
        params = [p for p in sample['params'] if p['name'] not in ('x', 'k')]
        out += [f'## {header} {{#{family}}}', '']
        out += ['| Parameter | Type | Default | Description |', '| --- | --- | --- | --- |']
        for p in params:
            default = f"`{p['default']}`" if p['default'] else 'required'
            out.append(f"| `${p['name']}` | `{p['type']}` | {default} | {cell(p['doc'])} |")
        point = 'k' if f'dist_{family}_pmf' in functions else 'x'
        out += ['', '| Function | Operation | Arguments | Returns |', '| --- | --- | --- | --- |']
        for op in ops:
            for batch in (False, True):
                name = f'dist_{family}_{op}' + ('_array' if batch else '')
                fn = functions[name]
                first = fn['params'][0]
                out.append(f"| [`{name}()`]{{#{name}}} | {OPERATION_TEXT[op]}{' over a list' if batch else ''} | "
                           f"`{first['type']} ${first['name']}`, parameters | `{fn['return_type']}` |")
        rng = functions[f'dist_{family}_rng']
        out.append(f"| [`dist_{family}_rng()`]{{#dist_{family}_rng}} | Seeded samples | `int $n`, `int $seed`, "
                   f"parameters | `{rng['return_type']}` |")
        out += ['', '```php', signature(sample), signature(functions[f'dist_{family}_cdf_array']), '```', '']
        out += [f'**Errors** {sample["throws"]}', '', f'**Sampler errors** {rng["throws"]}', '']
    return 'distributions', '\n'.join(out).rstrip() + '\n'


def csv_page(functions, classes):
    out = ['---', 'title: "CSV functions"', '---', '', GENERATED,
           'The native CSV reader, which requires the extension. See [Reading CSV files](../io.qmd) for options, '
           'types, missing values, and errors.', '', '## Reading a file', '']
    out += entry(functions['read_csv'])
    cls = classes['CsvReader']
    out += ['## Reading in chunks', '', '### `CsvReader` {#CsvReader}', '', ' '.join(cls['description']), '']
    for m in cls['methods']:
        anchor = 'CsvReader-' + m['name'].strip('_')
        ret = f": {m['return_type']}" if m['return_type'] else ''
        doc, tags = [], []
        for line in m['doc']:
            if line.startswith('@'):
                tags.append(line)
            elif tags:
                tags[-1] += ' ' + line.strip()
            else:
                doc.append(line)
        out += [f"#### `CsvReader::{m['name']}()` {{#{anchor}}}", '', ' '.join(doc), '', '```php',
                f"public function {m['name']}({m['args']}){ret}", '```', '']
        params = [t for t in tags if t.startswith('@param')]
        if params:
            out += ['| Parameter | Description |', '| --- | --- |']
            for t in params:
                pm = re.search(r'\$(\w+)\s*(.*)', t)
                out.append(f"| `${pm[1]}` | {cell(' '.join(pm[2].split()))} |")
            out.append('')
        for t in tags:
            if t.startswith('@return'):
                out += [f"**Returns** `{cell(t[len('@return'):].strip())}`", '']
            elif t.startswith('@throws'):
                out += [f"**Errors** {' '.join(t[len('@throws'):].replace(chr(92) + 'Exception', '').split())}", '']
    return 'csv', '\n'.join(out).rstrip() + '\n'


