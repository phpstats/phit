        discrete = f'dist_{family}_pmf' in functions
        ops = (DISCRETE if discrete else CONTINUOUS) + ['rng']
        cells = [f"[`{op}`](distributions.qmd#dist_{family}_{op})" for op in ops]
        header = FAMILY_NAMES[family]
        out.append(f"| [{header}](distributions.qmd#{family}) | " + ' | '.join(cells) + ' |')
